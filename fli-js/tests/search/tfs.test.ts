describe("fetchPayload retry", () => {
  const restoreSleep = () => _setPageRetrySleep(null);

  function pageWith(payload: unknown): string {
    return `<script>AF_initDataCallback({key: 'ds:1', hash: '1', data:${JSON.stringify(payload)}, sideChannel: {}});</script>`;
  }

  test("a page missing ds:1 once then present takes exactly 2 fetches", async () => {
    const slept: number[] = [];
    _setPageRetrySleep(async (ms) => {
      slept.push(ms);
    });
    try {
      let calls = 0;
      const client = new Client({
        retries: 1,
        fetchImpl: (async () => {
          calls++;
          return new Response(calls === 1 ? "<html>no payload</html>" : pageWith([1, 2]), {
            status: 200,
          });
        }) as unknown as typeof fetch,
      });
      expect(await fetchPayload(client, "https://example.com")).toEqual([1, 2]);
      expect(calls).toBe(2);
      expect(slept).toEqual([500]);
    } finally {
      restoreSleep();
    }
  });

  test("a page missing ds:1 every time gives up after exactly 3 fetches", async () => {
    const slept: number[] = [];
    _setPageRetrySleep(async (ms) => {
      slept.push(ms);
    });
    try {
      let calls = 0;
      const client = new Client({
        retries: 1,
        fetchImpl: (async () => {
          calls++;
          return new Response("<html>no payload</html>", { status: 200 });
        }) as unknown as typeof fetch,
      });
      expect(await fetchPayload(client, "https://example.com")).toBeNull();
      expect(calls).toBe(PAGE_FETCH_ATTEMPTS);
      expect(calls).toBe(3);
      // Backs off between attempts only, never after the last one.
      expect(slept).toEqual([500, 1500]);
    } finally {
      restoreSleep();
    }
  });

  test("a good page on the first try costs exactly one fetch and no sleep", async () => {
    const slept: number[] = [];
    _setPageRetrySleep(async (ms) => {
      slept.push(ms);
    });
    try {
      let calls = 0;
      const client = new Client({
        retries: 1,
        fetchImpl: (async () => {
          calls++;
          return new Response(pageWith(["ok"]), { status: 200 });
        }) as unknown as typeof fetch,
      });
      expect(await fetchPayload(client, "https://example.com")).toEqual(["ok"]);
      expect(calls).toBe(1);
      expect(slept).toEqual([]);
    } finally {
      restoreSleep();
    }
  });

  test("an HTTP error propagates on the first attempt — no page-level retry", async () => {
    let calls = 0;
    const client = new Client({
      retries: 1,
      fetchImpl: (async () => {
        calls++;
        return new Response("nope", { status: 503 });
      }) as unknown as typeof fetch,
    });
    await expect(fetchPayload(client, "https://example.com")).rejects.toThrow(/HTTP 503/);
    expect(calls).toBe(1);
  });
});

describe("applyClientSideFilters", () => {
  test("airline include keeps only matching carriers", () => {
    const kept = applyClientSideFilters(
      [flight({ airline: Airline.AA }), flight({ airline: Airline.DL })],
      filters([[["JFK"], ["LAX"], OUT]], { airlines: [Airline.AA] }),
    );
    expect(kept.map((f) => f.legs[0]?.airline)).toEqual([Airline.AA]);
  });

  test("airline exclude drops matching carriers", () => {
    const kept = applyClientSideFilters(
      [flight({ airline: Airline.AA }), flight({ airline: Airline.DL })],
      filters([[["JFK"], ["LAX"], OUT]], { airlines_exclude: [Airline.AA] }),
    );
    expect(kept.map((f) => f.legs[0]?.airline)).toEqual([Airline.DL]);
  });

  test("price cap drops expensive flights", () => {
    const kept = applyClientSideFilters(
      [flight({ price: 100 }), flight({ price: 900 })],
      filters([[["JFK"], ["LAX"], OUT]], { price_limit: { max_price: 500, currency: null } }),
    );
    expect(kept.map((f) => f.price)).toEqual([100]);
  });

  test("max duration drops long flights", () => {
    const kept = applyClientSideFilters(
      [flight({ duration: 120 }), flight({ duration: 600 })],
      filters([[["JFK"], ["LAX"], OUT]], { max_duration: 300 }),
    );
    expect(kept.map((f) => f.duration)).toEqual([120]);
  });

  test("departure window drops flights outside it", () => {
    const kept = applyClientSideFilters(
      [flight({ hour: 6 }), flight({ hour: 20 })],
      filters([[["JFK"], ["LAX"], OUT]], {
        time_restrictions: { earliest_departure: 8, latest_departure: 22 },
      }),
    );
    expect(kept.map((f) => f.legs[0]?.departure_datetime.getHours())).toEqual([20]);
  });

  test("the window follows the segment still being chosen", () => {
    // During round-trip expansion the outbound is pinned and the rows
    // coming back are return options. Filtering them against segment
    // zero's window drops valid returns and keeps invalid ones.
    const spec = new FlightSearchFilters({
      trip_type: TripType.ROUND_TRIP,
      passenger_info: pax(),
      flight_segments: [
        new FlightSegment({
          departure_airport: [[[Airport.JFK, 0]]],
          arrival_airport: [[[Airport.LAX, 0]]],
          travel_date: OUT,
          time_restrictions: { earliest_departure: 5, latest_departure: 9 },
          selected_flight: flight({ hour: 6 }),
        }),
        new FlightSegment({
          departure_airport: [[[Airport.LAX, 0]]],
          arrival_airport: [[[Airport.JFK, 0]]],
          travel_date: RET,
          time_restrictions: { earliest_departure: 18, latest_departure: 23 },
        }),
      ],
    });
    const kept = applyClientSideFilters([flight({ hour: 6 }), flight({ hour: 20 })], spec);
    expect(kept.map((f) => f.legs[0]?.departure_datetime.getHours())).toEqual([20]);
  });

  test("with nothing pinned, segment zero's window applies", () => {
    const spec = new FlightSearchFilters({
      trip_type: TripType.ROUND_TRIP,
      passenger_info: pax(),
      flight_segments: [
        new FlightSegment({
          departure_airport: [[[Airport.JFK, 0]]],
          arrival_airport: [[[Airport.LAX, 0]]],
          travel_date: OUT,
          time_restrictions: { earliest_departure: 5, latest_departure: 9 },
        }),
        new FlightSegment({
          departure_airport: [[[Airport.LAX, 0]]],
          arrival_airport: [[[Airport.JFK, 0]]],
          travel_date: RET,
          time_restrictions: { earliest_departure: 18, latest_departure: 23 },
        }),
      ],
    });
    const kept = applyClientSideFilters([flight({ hour: 6 }), flight({ hour: 20 })], spec);
    expect(kept.map((f) => f.legs[0]?.departure_datetime.getHours())).toEqual([6]);
  });

  test("a legless row cannot satisfy a window, and does not crash the search", () => {
    const legless = { ...flight(), legs: [] };
    const spec = filters([[["JFK"], ["LAX"], OUT]], {
      time_restrictions: { earliest_departure: 0, latest_departure: 23 },
    });
    expect(applyClientSideFilters([legless], spec)).toEqual([]);
  });

  test("no filters keeps everything", () => {
    const all = [flight({ airline: Airline.AA }), flight({ airline: Airline.DL })];
    expect(applyClientSideFilters(all, filters([[["JFK"], ["LAX"], OUT]]))).toEqual(all);
  });
});

