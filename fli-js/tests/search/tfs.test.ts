function flight(
  over: { airline?: Airline; price?: number | null; duration?: number; hour?: number } = {},
): FlightResult {
  const hour = over.hour ?? 9;
  const duration = over.duration ?? 180;
  return {
    legs: [
      leg({
        airline: over.airline ?? Airline.AA,
        departure_datetime: new Date(2030, 8, 15, hour, 0),
        arrival_datetime: new Date(2030, 8, 15, hour + 3, 0),
        duration,
      }),
    ],
    price: over.price === undefined ? 300 : over.price,
    currency: "USD",
    duration,
    stops: 0,
  };
}

function decode(tfs: string): Uint8Array {
  const padded = tfs + "=".repeat((4 - (tfs.length % 4)) % 4);
  return new Uint8Array(Buffer.from(padded.replace(/-/g, "+").replace(/_/g, "/"), "base64"));
}

/** Read the repeated field 8 (passenger kinds) out of a `tfs` token. */
function passengerCodes(tfs: string): number[] {
  const raw = decode(tfs);
  const codes: number[] = [];
  let offset = 0;
  const readVarint = (): number => {
    let value = 0;
    let shift = 0;
    while (true) {
      const byte = raw[offset] as number;
      offset++;
      value += (byte & 0x7f) * 2 ** shift;
      if ((byte & 0x80) === 0) return value;
      shift += 7;
    }
  };
  while (offset < raw.length) {
    const tag = readVarint();
    const field = tag >> 3;
    const wire = tag & 0x7;
    if (wire === 0) {
      const value = readVarint();
      if (field === 8) codes.push(value);
    } else if (wire === 2) {
      // `offset += readVarint()` would read `offset` before the call
      // mutates it, and skip from the wrong place.
      const length = readVarint();
      offset += length;
    } else {
      throw new Error(`unexpected wire type ${wire} at offset ${offset}`);
    }
  }
  return codes;
}

